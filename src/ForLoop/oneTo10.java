package ForLoop;

import java.util.Iterator;

public class oneTo10 {
	public static void main(String[] args) {
		for(int i=1;i<=10;i++) {
			System.out.println(i);
		}
		
		//from 10 down to 1 in reverse order.
		System.out.println("***********************");
		for(int i=10;i>
		0;i--) {
			System.out.println(i);
		}
	}

}
